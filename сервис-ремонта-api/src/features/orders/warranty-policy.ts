export const getRepairWarrantyExpiresAt = (issuedAt: Date): Date => {
  const year = issuedAt.getUTCFullYear() + 1;
  const month = issuedAt.getUTCMonth();
  const lastDayOfExpiryMonth = new Date(
    Date.UTC(year, month + 1, 0),
  ).getUTCDate();
  const day = Math.min(issuedAt.getUTCDate(), lastDayOfExpiryMonth);

  return new Date(
    Date.UTC(
      year,
      month,
      day,
      issuedAt.getUTCHours(),
      issuedAt.getUTCMinutes(),
      issuedAt.getUTCSeconds(),
      issuedAt.getUTCMilliseconds(),
    ),
  );
};
